"""给模型看的候选清单该按什么顺序排 —— **可游玩性分层**。

═══════════════════════════════════════════════════════════════
 这个模块解决什么（以及它为什么不叫「过滤器」）
═══════════════════════════════════════════════════════════════

问题：高德 `place/text` 的返回里有大量**不可能是行程站点**的东西。
实测（`scripts/probe_pool_quality.py`，2026-09-15，13 个关键词 × 20 条）：

| 关键词形态 | 池子有用率 | top-8 有用率 |
|---|---|---|
| 泛词/场景词（"古迹"/"博物馆"/"寺庙"） | 85.6% | 84.4% |
| **具体地名（"武侯祠"/"宽窄巷子"/"都江堰"）** | **43.3%** | **41.7%** |

最刺眼的一条：搜「都江堰」，前 8 条里只有 **1 条**是景点
（其余是市政府 / 客运中心 / 快铁站 / 火车站 / 医院 / 高速出口 / 道路名）。

**解法实测对比**（同一批数据，见那个脚本的 `- 策略对比` 一节）：

| 策略 | 窗口有用率 | 说明 |
|---|---|---|
| 现状（原序，不标注） | 76.9% | — |
| 硬黑名单过滤（剔 9 类硬噪音） | 90.4% | 会**误杀**：分类不可靠 |
| ✅ **按可游玩性重排（本模块）** | **98.1%** | 不删任何条目 |

**为什么选重排而不是过滤** —— 两条实测证据：

1. `type` / `typecode` **可以是 `|` 分隔的多值**。宽窄巷子景区的 `type` 是
   `购物服务;特色商业街;特色商业街|风景名胜;风景名胜相关;旅游景点` ——
   只看第一段会把它判成"购物服务"，**一个顶级景点就这么被过滤掉了**。
2. 高德的分类本身会错：`窄巷子`（宽窄巷子的组成部分）被归成"餐饮服务"，
   `宽窄巷子(B口)`（地铁口）也被归成"餐饮服务"。**规则再细也挡不住这种错**。

重排的代价只是"顺序"，不改变"池子里有什么" → **分类判错的后果从"丢地点"降级成"排后面"**。

═══════════════════════════════════════════════════════════════
 与「过滤掉噪音」的关系
═══════════════════════════════════════════════════════════════

排序**不删条目**，所以 `poi_pool` 里仍然是全量 —— 校验层的能力一点没少。
被排到后面的条目（地铁站 / 售票处）依然可以被引用、被算距离，
只是模型想选它时得往下翻。**这是故意的**：我们不确定分类一定错在哪，
所以宁可"让它排后面"也不"让它消失"。

═══════════════════════════════════════════════════════════════
 一个量不出来但确实存在的收益
═══════════════════════════════════════════════════════════════

"重排"能把窗口纯度从 76.9% 提到 98.1%，这是**可测量**的。
但还有一条测不出来：**在文本里带上类型标签**之后，模型知道第 3 条是"地铁站"
就不会选它 —— 这个收益无法用"窗口有用率"衡量（条目没变），
所以它是**零成本保险**，不是主要收益。两者一起做。
"""

from __future__ import annotations

from app.schemas import AmapPoi

#: 一级大类 → 可游玩性档位。**数字越小越像"能排进行程的地点"。**
#:
#: ⚠️ 这张表是**按需求形态**定的，不是按"好东西/坏东西"定的：
#: 「餐饮服务」搜"古迹"时是噪音、搜"火锅"时是目标 —— 所以它排在中档
#: 而不是被踢出去。分层只回答"如果只能给模型看几条，先给哪几条"。
RANK_BY_MAJOR: dict[str, int] = {
    "风景名胜": 0,      # 景点本体
    "公园广场": 0,
    "科教文化服务": 1,   # 博物馆 / 美术馆
    "体育休闲服务": 2,   # 游乐场 / 运动场馆
    "餐饮服务": 3,      # 吃
    "购物服务": 3,      # 逛（含"特色商业街"，宽窄巷子/太古里在这）
    "住宿服务": 4,      # 睡觉 —— 行程不排它，但将来"住宿推荐"要用
    # 其余（交通设施 / 地名地址 / 生活服务 / 政企 / 医疗 / 商务住宅 …）→ RANK_FALLBACK
}

#: 表里没有的一律落这一档。它**大于**所有具名档位，所以"不认识"永远排最后。
RANK_FALLBACK = 5

#: 末级类型里明确"不是游览对象"的词。**只用来否决整段，不用来定档。**
#:
#: 为什么需要它：`科教文化服务` 这一档里既有博物馆（该排前面），
#: 也有中学、驾校（该排最后）—— 只看一级大类会把它们混在一起。
#: 实测搜「都江堰」时前 8 里因此混进了 `四川省都江堰中学` 和 `都江堰考场`。
#:
#: 🔴 **维护原则：只在实测真的见到噪音时才加一条，不要凭想象往里塞。**
#: 这张表是补丁，不是分类体系 —— 一旦开始"顺手补全"，它就会变成一张
#: 永远追不上高德的清单，而且没人知道每条是为什么加的。
NON_VISIT_LEAVES = frozenset(
    {
        "学校", "中学", "小学", "大学", "高等院校", "职业技术学校",
        "驾校", "培训机构", "科研机构", "研究所",
    }
)


def _parts_of(type_str: str | None) -> list[list[str]]:
    """把 `type` 拆成 `[[段1层级...], [段2层级...], ...]`。

    **唯一一处拆分逻辑** —— `majors_of` / `rank_of` / `label_of` 全调它。
    理由：这三个函数对"什么算一段"必须完全一致，各写一份迟早漂移。
    """
    out: list[list[str]] = []
    for part in (type_str or "").split("|"):
        segs = [s.strip() for s in part.split(";") if s.strip()]
        if segs:
            out.append(segs)
    return out


def majors_of(type_str: str | None) -> list[str]:
    """`'购物服务;特色商业街;特色商业街|风景名胜;风景名胜相关;旅游景点'`
    → `['购物服务', '风景名胜']`。

    🔴 **必须先按 `|` 拆段**。实测 20 条里有 3 条是多值，而且多值条目的第 2 段
    往往才是它的真身份（宽窄巷子景区的第 2 段才是"风景名胜"）。
    少拆这一步的后果不是"排错几个"，是**把顶级景点判成购物场所**。

    ⚠️ 这个函数回答"它**属于**哪些大类"，是描述 —— 所以它**不看**
    `NON_VISIT_LEAVES`。要不要否决是 `rank_of` 的判断，两个问题不一样。
    """
    out: list[str] = []
    for segs in _parts_of(type_str):
        if segs[0] not in out:
            out.append(segs[0])
    return out


def rank_of(type_str: str | None) -> int:
    """取所有**可游览**段里最靠前的那一档。

    - 单值条目就是查表；多值取最优（`'购物服务|风景名胜'` 是 0 不是 3）
    - 末级命中 `NON_VISIT_LEAVES` 的段被**整段否决**（中学 / 驾校 → 排最后）
    - 所有段都被否决 → `RANK_FALLBACK`
    """
    ranks = [
        RANK_BY_MAJOR.get(segs[0], RANK_FALLBACK)
        for segs in _parts_of(type_str)
        if segs[-1] not in NON_VISIT_LEAVES
    ]
    return min(ranks) if ranks else RANK_FALLBACK


def label_of(type_str: str | None) -> str | None:
    """给模型看的**类型标签**，取最优那一段的末级：`'餐饮服务;中餐厅;火锅店'` → `'火锅店'`。

    取末级而不是一级大类，是因为末级信息量大得多：
    「中餐厅」和「火锅店」对"今晚吃什么"是完全不同的答案，而它们的一级大类都是「餐饮服务」。

    否决**只影响档位，不影响标签**：`科教文化服务;驾校;驾校` 的档位是最后，
    但标签仍然要如实显示「驾校」—— 那正是模型据以跳过它的信息。
    """
    parts = [segs for segs in _parts_of(type_str) if segs[-1] not in NON_VISIT_LEAVES]
    if not parts:
        # 全被否决时退回原样显示 —— 标签的职责是"告诉模型这是什么"，
        # 在这件事上它不该返回 None（那会让那一行看起来像"没有类型"）。
        originals = _parts_of(type_str)
        return originals[0][-1] if originals else None
    best = min(parts, key=lambda segs: RANK_BY_MAJOR.get(segs[0], RANK_FALLBACK))
    return best[-1]


def rank_pois(pois: list[AmapPoi]) -> list[AmapPoi]:
    """按可游玩性重排。**稳定排序** —— 同档内保持高德原始顺序。

    同档内不动是有意的：高德的原始顺序里含有我们读不出来的信号
    （它自己的相关性打分），重排**只该修正跨档的次序**，不该在档内自作聪明。
    实测也支持这一点：搜「都江堰」时目标（都江堰景区）本来就在第 1 条，
    档内重排只会把它搞乱。
    """
    return sorted(pois, key=lambda p: rank_of(p.type))


__all__ = [
    "NON_VISIT_LEAVES",
    "RANK_BY_MAJOR",
    "RANK_FALLBACK",
    "label_of",
    "majors_of",
    "rank_of",
    "rank_pois",
]
